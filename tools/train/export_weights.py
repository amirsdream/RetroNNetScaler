#!/usr/bin/env python3
"""Export TinySR classifier .pt → tinysr_weights.bin (+ optional .inc)."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

import torch

from model import TinySR


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", type=Path, required=True)
    ap.add_argument("--hlsl", type=Path, default=Path("../../shaders/tiny_sr_weights.inc"))
    ap.add_argument("--bin", type=Path, default=Path("../../build/tinysr_weights.bin"))
    args = ap.parse_args()

    ckpt = torch.load(args.ckpt, map_location="cpu", weights_only=False)
    ch = int(ckpt.get("channels", 16))
    scale = int(ckpt.get("scale", 4))
    ncls = int(ckpt.get("num_classes", 9))
    model = TinySR(channels=ch, scale=scale, dropout=0.0, num_classes=ncls)
    model.load_state_dict(ckpt["model"], strict=False)
    model.eval()

    def flat(t: torch.Tensor):
        return t.detach().cpu().contiguous().float().numpy().reshape(-1).tolist()

    order = [
        ("W1", model.conv1.weight),
        ("B1", model.conv1.bias),
        ("W2", model.conv2.weight),
        ("B2", model.conv2.bias),
        ("W3", model.conv3.weight),
        ("B3", model.conv3.bias),
    ]

    # Sanity: W3 out channels == 9 * scale^2
    assert model.conv3.out_channels == ncls * scale * scale, (
        f"W3 out={model.conv3.out_channels} expected {ncls * scale * scale}"
    )

    args.bin.parent.mkdir(parents=True, exist_ok=True)
    with args.bin.open("wb") as f:
        f.write(b"TNSR")
        f.write(struct.pack("<II", ch, scale))
        for _, t in order:
            arr = flat(t)
            f.write(struct.pack(f"<{len(arr)}f", *arr))
    print(f"Wrote {args.bin} (C={ch} scale={scale} classes={ncls})")

    lines = [
        "// Auto-generated by tools/train/export_weights.py — do not edit",
        f"static const uint kTinySrChannels = {ch};",
        f"static const uint kTinySrScale = {scale};",
        f"static const uint kTinySrClasses = {ncls};",
    ]
    for name, t in order:
        arr = flat(t)
        lines.append(f"static const uint k{name}Len = {len(arr)};")
        lines.append(f"static const float k{name}[{len(arr)}] = {{")
        row = []
        for i, v in enumerate(arr):
            row.append(f"{v:.8f}f")
            if len(row) == 8 or i == len(arr) - 1:
                lines.append("    " + ", ".join(row) + ("," if i != len(arr) - 1 else ""))
                row = []
        lines.append("};")
    args.hlsl.parent.mkdir(parents=True, exist_ok=True)
    args.hlsl.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.hlsl}")


if __name__ == "__main__":
    main()
